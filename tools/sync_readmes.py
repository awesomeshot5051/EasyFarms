#!/usr/bin/env python3
"""Keeps the README files the same on every version branch (master = 1.21.1, 26.1.2, ...).

The READMEs describe the mod, not one Minecraft version, so they must read the same on every branch. Two jobs:

  --update   Rewrites the generated version table between the <!-- versions:start --> and <!-- versions:end --> markers of README.md.
             The table lists every branch that has a gradle.properties with a minecraft_version (the current branch is read from the
             working tree, the others from their last commit), so a new branch or a version bump shows up by itself.
  --sync     Copies README.md and READMES/ from the current branch to every other version branch and commits them there. Uses a
             temporary git worktree, so your checked-out files are never touched. Skips a branch that is already identical.
  --install  Points git at tools/githooks (a one-time step per clone): the pre-commit hook runs --update when README.md or
             gradle.properties is part of a commit, and the post-commit hook runs --sync when README.md or READMES/ was committed.

The last README commit wins: if two branches change the README independently, the next commit on either overwrites the other.
"""
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

SYNC_PATHS = ["README.md", "READMES"]
START = "<!-- versions:start (generated by tools/sync_readmes.py: edit gradle.properties, not this table) -->"
END = "<!-- versions:end -->"
GUARD = "EASYFARMS_README_SYNC"


# Git exports GIT_DIR, GIT_INDEX_FILE... to hooks; they would point every git call below at the repo being committed to.
CLEAN_ENV = {k: v for k, v in os.environ.items() if not k.startswith("GIT_") or k == GUARD}


def run(args, cwd=None, check=True, env=None):
    return subprocess.run(args, cwd=cwd, check=check, capture_output=True, text=True, env=env or CLEAN_ENV)


def git(*args, cwd=None, check=True):
    return run(["git", *args], cwd=cwd, check=check).stdout


ROOT = Path(git("rev-parse", "--show-toplevel").strip())


def current_branch():
    return git("branch", "--show-current", cwd=ROOT).strip()


def props(text):
    out = {}
    for line in text.splitlines():
        m = re.match(r"\s*([A-Za-z0-9_.]+)\s*=\s*(.*?)\s*$", line)
        if m and not line.lstrip().startswith("#"):
            out[m.group(1)] = m.group(2)
    return out


def version_branches():
    """Branches that are a mod version: {branch: gradle properties}. The current branch is read from the working tree."""
    here = current_branch()
    found = {}
    for branch in git("for-each-ref", "--format=%(refname:short)", "refs/heads", cwd=ROOT).split():
        if branch == here and (ROOT / "gradle.properties").exists():
            text = (ROOT / "gradle.properties").read_text()
        else:
            text = git("show", f"{branch}:gradle.properties", cwd=ROOT, check=False)
        p = props(text)
        if "minecraft_version" in p:
            found[branch] = p
    return found


def sort_key(mc):
    # newest Minecraft first: compare the dotted numbers
    return [-int(n) if n.isdigit() else 0 for n in re.split(r"[.]", mc)]


def table():
    rows = sorted(version_branches().values(), key=lambda p: sort_key(p["minecraft_version"]))
    lines = ["| Minecraft | Mod loaders | Java | Easy Farms |", "|---|---|---|---|"]
    for p in rows:
        loaders = []
        if "neo_version" in p:
            loaders.append("NeoForge " + ".".join(p["neo_version"].split(".")[:-1] + ["x"]))
        if "fabric_loader_version" in p:
            loaders.append("Fabric")
        lines.append(f"| **{p['minecraft_version']}** | {', '.join(loaders)} | {p.get('java_version', '?')} | {p.get('mod_version', '?')} |")
    return "\n".join(lines)


def update():
    readme = ROOT / "README.md"
    text = readme.read_text()
    block = f"{START}\n{table()}\n{END}"
    if START in text and END in text:
        new = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda m: block, text, flags=re.S)
    else:
        sys.exit("README.md has no versions markers: add the START/END comment lines where the table should go")
    if new != text:
        readme.write_text(new)
        print("README.md: version table updated")
    return new != text


def sync():
    here = current_branch()
    targets = [b for b in version_branches() if b != here]
    for branch in targets:
        wt = Path(tempfile.mkdtemp(prefix="easyfarms-readme-"))
        try:
            added = run(["git", "worktree", "add", "--quiet", str(wt), branch], cwd=ROOT, check=False)
            if added.returncode != 0:
                print(f"{branch}: skipped ({added.stderr.strip().splitlines()[-1] if added.stderr.strip() else 'git worktree add failed'})")
                continue
            for name in SYNC_PATHS:
                src, dst = ROOT / name, wt / name
                if dst.is_dir():
                    shutil.rmtree(dst)
                elif dst.exists():
                    dst.unlink()
                if src.is_dir():
                    shutil.copytree(src, dst)
                elif src.exists():
                    shutil.copy2(src, dst)
            git("add", "-A", *SYNC_PATHS, cwd=wt)
            if run(["git", "diff", "--cached", "--quiet"], cwd=wt, check=False).returncode == 0:
                print(f"{branch}: README already up to date")
            else:
                run(["git", "commit", "--quiet", "--no-verify", "-m", f"Sync README from {here}"], cwd=wt, env=dict(CLEAN_ENV, **{GUARD: "1"}))
                print(f"{branch}: README synced from {here}")
        finally:
            run(["git", "worktree", "remove", "--force", str(wt)], cwd=ROOT, check=False)
            shutil.rmtree(wt, ignore_errors=True)


def install():
    git("config", "core.hooksPath", "tools/githooks", cwd=ROOT)
    for hook in (ROOT / "tools" / "githooks").glob("*"):
        hook.chmod(0o755)
    print("git hooks installed (core.hooksPath = tools/githooks)")


if __name__ == "__main__":
    modes = {"--update": update, "--sync": sync, "--install": install}
    if len(sys.argv) != 2 or sys.argv[1] not in modes:
        sys.exit(__doc__)
    modes[sys.argv[1]]()
